/// Tables the Rust service owns and creates itself (`migrations/rust-owned/`, see
/// `store::postgres::RUST_OWNED_MIGRATIONS`), outside alembic: alembic does not know them and
/// `alembic_version` never changes for them. Not in [`ALL_TABLES`], which mirrors alembic head.
pub static RUST_OWNED_TABLES: &[&TableDef] = &[&NESSIE_SIMULATION_RECORDS, &OWNER_INTRO_RECORDINGS];

#[cfg(test)]
mod tests {
    use super::*;

    const MIGRATIONS: [&str; 2] = [
        include_str!("../../migrations/0001_foundation_schema.sql"),
        include_str!("../../migrations/0002_owner_channels.sql"),
    ];

    /// The CREATE TABLE statement for `name` in the migrations, as lines.
    fn ddl(name: &str) -> Vec<String> {
        let all = MIGRATIONS.join("\n");
        let start = all
            .find(&format!("CREATE TABLE {name} ("))
            .unwrap_or_else(|| panic!("no CREATE TABLE {name}"));
        let end = start + all[start..].find("\n);").expect("end of CREATE TABLE");
        all[start..end]
            .lines()
            .skip(1)
            .map(|l| l.trim().trim_end_matches(',').to_owned())
            .collect()
    }

    fn sql_type(ty: ColType) -> String {
        match ty {
            ColType::Uuid => "UUID".into(),
            ColType::Varchar(n) => format!("VARCHAR({n})"),
            ColType::Text => "TEXT".into(),
            ColType::Int => "INTEGER".into(),
            ColType::BigInt => "BIGINT".into(),
            ColType::Bool => "BOOLEAN".into(),
            ColType::Float => "FLOAT".into(),
            ColType::Json => "JSONB".into(),
            ColType::Timestamp => "TIMESTAMP WITH TIME ZONE".into(),
        }
    }

    #[test]
    fn metadata_matches_the_alembic_ddl() {
        assert_eq!(ALL_TABLES.len(), 28);
        let all = MIGRATIONS.join("\n");
        assert_eq!(all.matches("CREATE TABLE ").count(), 28);
        for t in ALL_TABLES {
            let lines = ddl(t.name);
            let col_lines: Vec<&String> = lines
                .iter()
                .filter(|l| !l.starts_with("CONSTRAINT"))
                .collect();
            assert_eq!(col_lines.len(), t.columns.len(), "{}: column count", t.name);
            for (c, line) in t.columns.iter().zip(&col_lines) {
                let mut want = format!("{} {}", c.name, sql_type(c.ty));
                if c.default == ColDefault::Identity {
                    want.push_str(" GENERATED BY DEFAULT AS IDENTITY");
                } else {
                    if c.default == ColDefault::Now {
                        want.push_str(" DEFAULT now()");
                    }
                    if !c.nullable {
                        want.push_str(" NOT NULL");
                    }
                }
                assert_eq!(line.as_str(), want, "{}.{}", t.name, c.name);
            }
            assert!(
                lines.contains(&format!("CONSTRAINT pk_{} PRIMARY KEY (id)", t.name)),
                "{} pk",
                t.name
            );
            for u in t.uniques {
                let want = format!("CONSTRAINT {} UNIQUE ({})", u.name, u.columns.join(", "));
                assert!(lines.contains(&want), "{}: {want}", t.name);
            }
            for f in t.foreign_keys {
                let rule = match f.on_delete {
                    OnDelete::Cascade => "CASCADE",
                    OnDelete::Restrict => "RESTRICT",
                    OnDelete::SetNull => "SET NULL",
                };
                let want = format!(
                    "CONSTRAINT {} FOREIGN KEY({}) REFERENCES {} (id) ON DELETE {rule}",
                    f.name, f.column, f.references
                );
                assert!(lines.contains(&want), "{}: {want}", t.name);
            }
            let constraints = lines.iter().filter(|l| l.starts_with("CONSTRAINT")).count();
            assert_eq!(
                constraints,
                1 + t.uniques.len() + t.foreign_keys.len(),
                "{} constraints",
                t.name
            );
            for i in t.indexes {
                let want = format!(
                    "CREATE INDEX {} ON {} ({});",
                    i.name,
                    t.name,
                    i.columns.join(", ")
                );
                assert!(all.contains(&want), "{want}");
            }
            let n_idx = all.matches(&format!(" ON {} (", t.name)).count();
            assert_eq!(n_idx, t.indexes.len(), "{} index count", t.name);
        }
    }
}
