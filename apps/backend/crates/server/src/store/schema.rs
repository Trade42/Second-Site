//! Static table metadata: a port of `apps/api/app/db/models.py`, matching the alembic-head schema
//! (`migrations/0001_*.sql`, `0002_*.sql`) column for column, with the same constraint names.
//!
//! To add a table: declare it here with [`doc_table!`] (rows that store a contract in `data`) or
//! [`plain_table!`], list it in [`ALL_TABLES`], and add a migration. Nothing else in the store
//! changes.

/// Column types (PostgreSQL names in comments).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ColType {
    /// `UUID`
    Uuid,
    /// `VARCHAR(n)`
    Varchar(u32),
    /// `TEXT`
    Text,
    /// `INTEGER` (32-bit)
    Int,
    /// `BIGINT`
    BigInt,
    /// `BOOLEAN`
    Bool,
    /// `FLOAT` (double precision)
    Float,
    /// `JSONB`
    Json,
    /// `TIMESTAMP WITH TIME ZONE`
    Timestamp,
}

impl ColType {
    /// The `information_schema.columns.data_type` PostgreSQL reports.
    pub fn pg_data_type(&self) -> &'static str {
        match self {
            ColType::Uuid => "uuid",
            ColType::Varchar(_) => "character varying",
            ColType::Text => "text",
            ColType::Int => "integer",
            ColType::BigInt => "bigint",
            ColType::Bool => "boolean",
            ColType::Float => "double precision",
            ColType::Json => "jsonb",
            ColType::Timestamp => "timestamp with time zone",
        }
    }
}

/// Where a column's value comes from when an insert omits it.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum ColDefault {
    /// No default: the insert must provide it (or it is NULL when nullable).
    None,
    /// `server_default=now()` (transaction time).
    Now,
    /// `GENERATED BY DEFAULT AS IDENTITY`.
    Identity,
    /// SQLAlchemy Python-side default.
    Text(&'static str),
    Int(i64),
    Bool(bool),
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Column {
    pub name: &'static str,
    pub ty: ColType,
    pub nullable: bool,
    pub default: ColDefault,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum OnDelete {
    Cascade,
    Restrict,
    SetNull,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ForeignKey {
    pub name: &'static str,
    pub column: &'static str,
    pub references: &'static str,
    pub on_delete: OnDelete,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Unique {
    pub name: &'static str,
    pub columns: &'static [&'static str],
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Index {
    pub name: &'static str,
    pub columns: &'static [&'static str],
}

/// One table. The primary key is always the `id UUID` column, named `pk_<table>`.
#[derive(Debug, PartialEq)]
pub struct TableDef {
    pub name: &'static str,
    pub columns: &'static [Column],
    pub uniques: &'static [Unique],
    pub foreign_keys: &'static [ForeignKey],
    pub indexes: &'static [Index],
    /// Has the `DocumentMixin` columns (`data`, `schema_version`, `record_version`).
    pub document: bool,
}

impl TableDef {
    pub fn column(&self, name: &str) -> Option<&'static Column> {
        self.columns.iter().find(|c| c.name == name)
    }

    pub fn has_column(&self, name: &str) -> bool {
        self.column(name).is_some()
    }

    pub fn primary_key_name(&self) -> String {
        format!("pk_{}", self.name)
    }

    /// Column list in DDL order, comma separated (for SQL generation; names are static).
    pub fn column_list(&self) -> String {
        self.columns
            .iter()
            .map(|c| c.name)
            .collect::<Vec<_>>()
            .join(", ")
    }
}

const fn col(name: &'static str, ty: ColType, nullable: bool) -> Column {
    Column {
        name,
        ty,
        nullable,
        default: ColDefault::None,
    }
}

const fn uuid(name: &'static str) -> Column {
    col(name, ColType::Uuid, false)
}
const fn uuid_null(name: &'static str) -> Column {
    col(name, ColType::Uuid, true)
}
const fn varchar(name: &'static str, n: u32) -> Column {
    col(name, ColType::Varchar(n), false)
}
const fn varchar_null(name: &'static str, n: u32) -> Column {
    col(name, ColType::Varchar(n), true)
}
const fn int(name: &'static str) -> Column {
    col(name, ColType::Int, false)
}
const fn boolean(name: &'static str) -> Column {
    col(name, ColType::Bool, false)
}
/// SQLAlchemy `default=False` (Python-side; the DDL has no default).
const fn boolean_false(name: &'static str) -> Column {
    Column {
        name,
        ty: ColType::Bool,
        nullable: false,
        default: ColDefault::Bool(false),
    }
}
const fn float(name: &'static str) -> Column {
    col(name, ColType::Float, false)
}
const fn float_null(name: &'static str) -> Column {
    col(name, ColType::Float, true)
}
const fn json(name: &'static str) -> Column {
    col(name, ColType::Json, false)
}
const fn text(name: &'static str) -> Column {
    col(name, ColType::Text, false)
}

